#!/usr/bin/env node
/**
 * Write site/src/kairos-identity-constants.js from built identity WASM.
 * Delegate key = blake3(code_hash_bytes) — same as GitForge / microblogging.
 * Usage: node scripts/gen-identity-constants.mjs <kairos_identity.wasm> [code_hash_b58]
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..");
const wasmPath = process.argv[2];
const codeB58Arg = process.argv[3];
if (!wasmPath) {
  console.error("usage: gen-identity-constants.mjs <wasm> [code_hash_b58]");
  process.exit(1);
}

const require = createRequire(join(root, "site/package.json"));
const { blake3 } = require("@noble/hashes/blake3");
const bs58mod = require("bs58");
const bs58 = bs58mod.default ?? bs58mod;

let codeBytes;
let codeB58;
if (codeB58Arg) {
  codeBytes = Array.from(bs58.decode(codeB58Arg));
  codeB58 = codeB58Arg;
} else {
  const wasm = readFileSync(wasmPath);
  const digest = blake3(wasm);
  codeBytes = Array.from(digest);
  codeB58 = bs58.encode(digest);
}

const keyDigest = blake3(Uint8Array.from(codeBytes));
const keyBytes = Array.from(keyDigest);

const outDir = join(root, "site/src");
mkdirSync(outDir, { recursive: true });
writeFileSync(
  join(outDir, "kairos-identity-constants.js"),
  `/* AUTO-GENERATED by scripts/gen-identity-constants.mjs — do not edit */
export const KAIROS_IDENTITY_CODE_HASH_B58 = ${JSON.stringify(codeB58)};
export const KAIROS_IDENTITY_CODE_HASH_BYTES = [${codeBytes.join(",")}];
export const KAIROS_IDENTITY_KEY_BYTES = [${keyBytes.join(",")}];
export const KAIROS_IDENTITY_WASM_PATH = "./public/kairos_identity.wasm";

export function kairosIdentityReady() {
  return (
    Array.isArray(KAIROS_IDENTITY_CODE_HASH_BYTES) &&
    KAIROS_IDENTITY_CODE_HASH_BYTES.length === 32 &&
    Array.isArray(KAIROS_IDENTITY_KEY_BYTES) &&
    KAIROS_IDENTITY_KEY_BYTES.length === 32
  );
}
`,
);
console.log("wrote site/src/kairos-identity-constants.js", codeB58);
