#!/usr/bin/env node
/**
 * Write site/src/kairos-constants.js from built WASM blake3.
 * Usage: node scripts/gen-constants.mjs <kairos_time.wasm>
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..");
const wasmPath = process.argv[2];
if (!wasmPath) {
  console.error("usage: gen-constants.mjs <wasm>");
  process.exit(1);
}

const require = createRequire(join(root, "site/package.json"));
const { blake3 } = require("@noble/hashes/blake3");
const bs58 = require("bs58");

const wasm = readFileSync(wasmPath);
const hashBytes = Buffer.from(blake3(wasm));
const hashB58 = bs58.default?.encode
  ? bs58.default.encode(hashBytes)
  : bs58.encode(hashBytes);

const hashArr = Array.from(hashBytes);
const outDir = join(root, "site/src");
mkdirSync(outDir, { recursive: true });
mkdirSync(join(root, "build"), { recursive: true });

writeFileSync(
  join(outDir, "kairos-constants.js"),
  `/* AUTO-GENERATED by scripts/gen-constants.mjs — do not edit */
export const KAIROS_PARAMS_UTF8 = "kairos-time-v2";
export const KAIROS_WASM_HASH_B58 = ${JSON.stringify(hashB58)};
export const KAIROS_WASM_HASH_BYTES = [${hashArr.join(",")}];
export const KAIROS_WASM_PATH = "./public/kairos_time.wasm";
`,
);
writeFileSync(
  join(root, "build/owner-tools-info.md"),
  [
    "# Kairos build fingerprint",
    "",
    "| Artifact | Value |",
    "|----------|-------|",
    `| WASM BLAKE3 (b58) | \`${hashB58}\` |`,
    "| Params UTF-8 | `kairos-time-v2` |",
    "",
  ].join("\n"),
);
console.log("wrote site/src/kairos-constants.js", hashB58);
